"""Regenerate docs/CURRENT-STATE.md from the checkout.

Run this instead of hand-editing test counts or table counts in docs.
"""
from __future__ import annotations

import re
import sqlite3
import subprocess
import sys
from datetime import date
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "docs" / "CURRENT-STATE.md"


def _git(*args: str) -> str:
    try:
        return subprocess.check_output(
            ["git", *args], cwd=PROJECT_ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except Exception:
        return ""


def _test_count() -> int | None:
    completed = subprocess.run(
        [sys.executable, "-m", "pytest", "tests", "--collect-only"],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
    )
    match = re.search(r"(\d+)\s+tests?\s+collected", completed.stdout + completed.stderr)
    return int(match.group(1)) if match else None


def _table_count() -> int | None:
    db_path = PROJECT_ROOT / "data" / "captures.db"
    if not db_path.exists():
        return None
    with sqlite3.connect(db_path) as conn:
        names = [
            row[0]
            for row in conn.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
            )
        ]
    shadow = {
        "capture_search_fts_data",
        "capture_search_fts_idx",
        "capture_search_fts_content",
        "capture_search_fts_docsize",
        "capture_search_fts_config",
    }
    return len([name for name in names if name not in shadow])


def main() -> int:
    tests = _test_count()
    tables = _table_count()
    branch = _git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"
    lines = [
        "# Current State",
        "",
        "> Generated by `scripts/update_current_state.py`. Do not hand-edit counts.",
        "",
        f"- Date: {date.today().isoformat()}",
        f"- Branch: `{branch}`",
        "- Commit: see `git log -1` (this file is generated before its own commit)",
        f"- Tests collected: {tests if tests is not None else 'unknown'}",
        f"- SQLite business tables: {tables if tables is not None else 'data/captures.db not found'}",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
